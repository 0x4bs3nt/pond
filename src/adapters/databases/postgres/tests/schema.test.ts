import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import type { DatabaseResult } from '../../../../domain/database';
import type { DatabaseSession } from '../../../../ports/database';
import { postgresDatabaseAdapter } from '../adapter';
import { postgresAvailable, startPostgres } from './fixture';

const value = <T extends unknown>(result: DatabaseResult<T>): T => {
    if (!result.ok) throw new Error(result.error.code);
    return result.value;
};

describe.skipIf(!postgresAvailable)('PostgreSQL catalog metadata', () => {
    let fixture: Awaited<ReturnType<typeof startPostgres>>;
    let session: DatabaseSession;
    const connect = async (user = 'pond') =>
        value(
            await postgresDatabaseAdapter.connect({
                engineId: 'postgres',
                database: 'postgres',
                network: { host: '127.0.0.1', port: fixture.port, user, tls: 'disable' },
            })
        );
    beforeAll(async () => {
        fixture = await startPostgres();
        await fixture.client.query(`
            CREATE SCHEMA "Odd.Schema";
            CREATE SCHEMA empty_schema;
            CREATE DOMAIN "Odd.Schema".amount AS numeric(12,3) DEFAULT 7.5 NOT NULL;
            CREATE DOMAIN "Odd.Schema".nested_amount AS "Odd.Schema".amount;
            CREATE TYPE "Odd.Schema".status AS ENUM ('draft', 'ready');
            CREATE TABLE "Odd.Schema"."select" (
                second bigint NOT NULL,
                discarded text,
                "First Key" integer GENERATED BY DEFAULT AS IDENTITY,
                price numeric(24,6) DEFAULT 123.456,
                required "Odd.Schema".nested_amount,
                computed numeric GENERATED ALWAYS AS (price * 2) STORED,
                tags text[], label "Odd.Schema".status, data jsonb DEFAULT '{}',
                "always" bigint GENERATED ALWAYS AS IDENTITY,
                PRIMARY KEY ("First Key", second)
            );
            ALTER TABLE "Odd.Schema"."select" DROP COLUMN discarded;
            CREATE VIEW "Odd.Schema"."Read view" AS SELECT second, price FROM "Odd.Schema"."select";
            CREATE MATERIALIZED VIEW "Odd.Schema".summary AS SELECT 1 AS count;
            CREATE TABLE "Odd.Schema".zero_columns ();
            CREATE TABLE "Odd.Schema".partitioned (id integer) PARTITION BY RANGE(id);
            CREATE TABLE "Odd.Schema"."x'; SELECT 1; --" ("a.b" text);
            CREATE ROLE catalog_reader LOGIN;
            GRANT USAGE ON SCHEMA "Odd.Schema" TO catalog_reader;
            GRANT SELECT (second) ON "Odd.Schema"."select" TO catalog_reader;
        `);
        session = await connect();
    }, 20000);
    afterAll(async () => {
        await session?.close();
        await fixture?.stop();
    });

    test('keeps quoted identifiers, native types, domain rules and ordered write metadata exact', async () => {
        const namespaces = value(await session.schema.listNamespaces());
        expect(namespaces).toContainEqual(['Odd.Schema']);
        expect(namespaces).toContainEqual(['empty_schema']);
        expect(namespaces.some(([name]) => name!.startsWith('pg_') || name === 'information_schema')).toBe(false);
        expect(value(await session.schema.listTables(['empty_schema']))).toEqual([]);
        const tables = value(await session.schema.listTables(['Odd.Schema']));
        expect(tables.find((table) => table.name === 'Read view')?.kind).toBe('view');
        expect(tables.find((table) => table.name === 'summary')?.kind).toBe('materialized-view');
        expect(tables.find((table) => table.name === 'partitioned')?.kind).toBe('table');
        const schema = value(await session.schema.describeTable({ namespace: ['Odd.Schema'], name: 'select' }));
        expect(schema.columns.map((column) => column.name)).toEqual([
            'second',
            'First Key',
            'price',
            'required',
            'computed',
            'tags',
            'label',
            'data',
            'always',
        ]);
        expect(schema.primaryKey).toEqual(['3', '1']);
        expect(schema.columns[1]).toMatchObject({ nullable: false, identity: 'by-default', defaultExpression: null });
        expect(schema.columns[2]).toMatchObject({
            nativeType: 'numeric(24,6)',
            nullable: true,
            category: 'decimal',
            defaultExpression: '123.456',
        });
        expect(schema.columns[3]).toMatchObject({
            nativeType: '"Odd.Schema".nested_amount',
            nullable: false,
            category: 'decimal',
            defaultExpression: '7.5',
        });
        expect(schema.columns[4]).toMatchObject({ defaultExpression: null, generated: { kind: 'stored' } });
        expect(schema.columns[4]?.generated?.expression).toContain('price');
        expect(schema.columns[5]).toMatchObject({ nativeType: 'text[]', category: 'other' });
        expect(schema.columns[6]).toMatchObject({ nativeType: '"Odd.Schema".status', category: 'other' });
        expect(schema.columns[8]?.identity).toBe('always');
        const quoted = value(
            await session.schema.describeTable({ namespace: ['Odd.Schema'], name: "x'; SELECT 1; --" })
        );
        expect(quoted.columns[0]?.name).toBe('a.b');
        expect(
            value(await session.schema.describeTable({ namespace: ['Odd.Schema'], name: 'zero_columns' })).columns
        ).toEqual([]);
        expect(
            value(await session.schema.describeTable({ namespace: ['Odd.Schema'], name: 'Read view' })).primaryKey
        ).toEqual([]);
    });

    test('a cleared nested-domain default stays absent while column defaults still take precedence', async () => {
        await fixture.client.query(`
            CREATE DOMAIN "Odd.Schema".base_default AS integer DEFAULT 7;
            CREATE DOMAIN "Odd.Schema".cleared_default AS "Odd.Schema".base_default;
            ALTER DOMAIN "Odd.Schema".cleared_default DROP DEFAULT;
            CREATE TABLE "Odd.Schema".domain_defaults (
                inherited "Odd.Schema".base_default,
                cleared "Odd.Schema".cleared_default,
                overridden "Odd.Schema".cleared_default DEFAULT 9
            );
        `);
        const schema = value(
            await session.schema.describeTable({ namespace: ['Odd.Schema'], name: 'domain_defaults' })
        );
        const inserted = await fixture.client.query(
            'INSERT INTO "Odd.Schema".domain_defaults DEFAULT VALUES RETURNING *'
        );
        expect(inserted.rows[0]).toEqual({ inherited: 7, cleared: null, overridden: 9 });
        expect(schema.columns.map((column) => column.defaultExpression)).toEqual(['7', null, '9']);
    });

    test('respects visibility and handles removed relations and closed sessions safely', async () => {
        const reader = await connect('catalog_reader');
        try {
            expect(value(await reader.schema.listTables(['Odd.Schema'])).map((table) => table.name)).toEqual([
                'select',
            ]);
            expect(
                value(await reader.schema.describeTable({ namespace: ['Odd.Schema'], name: 'select' })).primaryKey
            ).toEqual(['3', '1']);
            expect(await reader.schema.describeTable({ namespace: ['Odd.Schema'], name: 'summary' })).toEqual({
                ok: false,
                error: { code: 'permission-denied' },
            });
            await fixture.client.query('DROP VIEW "Odd.Schema"."Read view"');
            expect(await session.schema.describeTable({ namespace: ['Odd.Schema'], name: 'Read view' })).toEqual({
                ok: false,
                error: { code: 'not-found' },
            });
            expect(await session.schema.describeTable({ namespace: ['Odd', 'Schema'], name: 'select' })).toEqual({
                ok: false,
                error: { code: 'invalid-request' },
            });
        } finally {
            await reader.close();
        }
        expect(await reader.schema.listNamespaces()).toEqual({ ok: false, error: { code: 'closed' } });
    });
});
